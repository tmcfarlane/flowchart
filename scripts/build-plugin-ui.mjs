import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
const result = await build({ entryPoints: ['src/plugin-ui/card.ts'], bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2020', minify: true, drop: ['console'] })
await mkdir('src/shared/server', { recursive: true })
await writeFile('src/shared/server/pluginUi.generated.ts', '// Generated by npm run plugin:ui. Do not edit.\nexport const CARD_SCRIPT = ' + JSON.stringify(result.outputFiles[0].text) + '\n')
