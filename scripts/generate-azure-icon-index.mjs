#!/usr/bin/env node
// Generates src/shared/generated/azure-icon-index.json from assets/icons/**/*.svg.
//
// The browser resolves icons with Vite's import.meta.glob, which server code
// (the MCP server and REST API on Vercel) cannot use. This static index gives
// the server the same stable icon ids the browser uses.
//
// Runs automatically before `npm run dev` and `npm run build`. The unit test
// src/test/shared/icons.test.ts fails if the committed index is stale.
//
// Keep iconNameFromFile/slugifyIconName in sync with src/shared/iconIds.ts
// (a unit test checks that both produce the same ids).

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ICONS_DIR = join(ROOT, 'assets', 'icons')
export const OUTPUT_FILE = join(ROOT, 'src', 'shared', 'generated', 'azure-icon-index.json')

/** "10035-icon-service-App-Services.svg" -> "App-Services" */
export function iconNameFromFile(fileName) {
  return fileName
    .replace(/\.svg$/i, '')
    .replace(/^\d+-/, '')
    .replace(/^icon-service-/i, '')
    .replace(/\s+color icon$/i, '')
    .replace(/\s+icon$/i, '')
    .trim()
}

/** "App-Services" -> "app-services", "Web-Application-Firewall-Policies(WAF)" -> "web-application-firewall-policies-waf" */
export function slugifyIconName(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else if (entry.isFile() && entry.name.toLowerCase().endsWith('.svg')) out.push(full)
  }
  return out
}

export function buildIconIndex() {
  const files = walk(ICONS_DIR)
    .map((full) => '/' + relative(ROOT, full).split(sep).join('/'))
    .sort()

  const seen = new Set()
  const icons = []
  for (const path of files) {
    const parts = path.split('/')
    const fileName = parts[parts.length - 1]
    const category = parts[parts.length - 2] || 'other'
    const rawName = iconNameFromFile(fileName)
    const id = slugifyIconName(rawName)
    // Some services ship in several categories; the first path (sorted) wins,
    // matching the browser, which resolves ids the same way.
    if (!id || seen.has(id)) continue
    seen.add(id)
    icons.push({
      id,
      name: rawName.replace(/[-_]+/g, ' ').replace(/\s+/g, ' ').trim(),
      category,
      path,
    })
  }

  return {
    description:
      'Generated by scripts/generate-azure-icon-index.mjs from assets/icons. Do not edit by hand.',
    count: icons.length,
    icons,
  }
}

export function serializeIconIndex(index) {
  return JSON.stringify(index, null, 2) + '\n'
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const next = serializeIconIndex(buildIconIndex())
  let current = ''
  try {
    current = readFileSync(OUTPUT_FILE, 'utf-8')
  } catch {
    // first run
  }
  if (current === next) {
    console.log(`[icons] Azure icon index is up to date (${JSON.parse(next).count} icons).`)
  } else {
    mkdirSync(dirname(OUTPUT_FILE), { recursive: true })
    writeFileSync(OUTPUT_FILE, next)
    console.log(`[icons] Wrote ${relative(ROOT, OUTPUT_FILE)} (${JSON.parse(next).count} icons).`)
  }
}
